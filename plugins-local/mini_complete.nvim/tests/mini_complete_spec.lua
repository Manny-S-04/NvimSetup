end)

-- ── accepting ───────────────────────────────────────────────────────────────────────────────────
test('accept inserts the label and puts the cursor after it; the bar does not reopen on it', function()
  local mc = H.reset()
  mc.setup({ luasnip = false })
  H.buffer(H.fake_server({ complete = function() return items({ label = 'Console' }) end }))
  H.feed('ivar c = Con')
  H.wait_until(mc.is_visible)
  H.feed('<CR>')
  H.sleep(100)
  eq('var c = Console', line())
  eq(#'var c = Console', vim.api.nvim_win_get_cursor(0)[2])
  eq(false, mc.is_visible(), 'not reopened by its own insertion')
end)

test('itemDefaults.editRange + textEditText: inserts the edit text, not the label (Task<> -> Task)', function()
  local mc = H.reset()
  mc.setup({ luasnip = false })
  H.buffer(H.fake_server({ complete = function(p)
    local pos = p.position
    return {
      isIncomplete = false,
      itemDefaults = { editRange = { start = { line = pos.line, character = pos.character - 2 }, ['end'] = pos } },
      items = { { label = 'Task<>', textEditText = 'Task' } },
    }
  end }))
  H.feed('iTa')
  H.wait_until(mc.is_visible)
  H.feed('<CR>')
  H.sleep(100)
  eq('Task', line())
end)

