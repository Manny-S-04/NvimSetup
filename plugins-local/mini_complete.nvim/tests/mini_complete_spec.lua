local H = require('helpers')
local test, eq, ok = H.test, H.eq, H.ok

local function items(...) return { isIncomplete = false, items = { ... } } end
local function line() return vim.api.nvim_get_current_line() end

-- ── setup ────────────────────────────────────────────────────────────────────────────────────────
test('setup merges options over the defaults without dropping the rest', function()
  local mc = H.reset()
  mc.setup({ min_prefix = 2, keymaps = { next = '<Tab>' } })
  eq(2, mc.config.min_prefix)
  eq('<Tab>', mc.config.keymaps.next)
  eq('<C-k>', mc.config.keymaps.prev, 'untouched keymap kept')
  eq(30, mc.config.debounce_ms, 'untouched option kept')
  eq({ '.', '->', '::' }, mc.config.trigger_characters)
end)

test('highlights link to the popup-menu groups, overrides win, and both survive a colorscheme change', function()
  local mc = H.reset()
  mc.setup({ luasnip = false, highlights = { MiniCompleteSelected = { bg = '#123456' } } })
  eq('Pmenu', vim.api.nvim_get_hl(0, { name = 'MiniCompleteNormal' }).link)
  eq(tonumber('123456', 16), vim.api.nvim_get_hl(0, { name = 'MiniCompleteSelected' }).bg)
  vim.cmd('hi clear')
  vim.api.nvim_exec_autocmds('ColorScheme', {})
  eq('Pmenu', vim.api.nvim_get_hl(0, { name = 'MiniCompleteNormal' }).link)
  eq(tonumber('123456', 16), vim.api.nvim_get_hl(0, { name = 'MiniCompleteSelected' }).bg)
end)

-- ── opening and filtering ────────────────────────────────────────────────────────────────────────
test('opens after typing a prefix, filters case-insensitively and sorts by sortText', function()
  local mc = H.reset()
  mc.setup({ luasnip = false })
  local server = H.fake_server({ complete = function()
    return items({ label = 'TaskCanceledException', sortText = 'b' }, { label = 'task', sortText = 'a' }, { label = 'Other' })
  end })
  H.buffer(server)
  H.feed('ita')
  ok(H.wait_until(mc.is_visible), 'bar opened')
  eq({ 'task', 'TaskCanceledException' }, H.labels(mc._state.items))
end)

test('the bar is a named, unmodifiable scratch buffer showing the items', function()
  local mc = H.reset()
  mc.setup({ luasnip = false })
  H.buffer(H.fake_server({ complete = function() return items({ label = 'Alpha' }, { label = 'Alps' }) end }))
  H.feed('iAl')
  H.wait_until(mc.is_visible)
  local buf = mc._state.buf
  eq('mini-complete://bar', vim.api.nvim_buf_get_name(buf))
  eq('nofile', vim.bo[buf].buftype)
  eq(false, vim.bo[buf].modifiable)
  local text = table.concat(vim.api.nvim_buf_get_lines(buf, 0, -1, false), '\n')
  ok(text:find('Alpha') and text:find('Alps'), 'labels rendered: ' .. text)
end)

test('min_prefix: no request until enough characters are typed', function()
  local mc = H.reset()
  mc.setup({ luasnip = false, min_prefix = 3 })
  local server = H.fake_server({ complete = function() return items({ label = 'Alpha' }) end })
  H.buffer(server)
  H.feed('iAl')
  H.sleep(150)
  eq(0, server.count('textDocument/completion'))
  H.feed('p')
  ok(H.wait_until(mc.is_visible), 'opens at 3 characters')
end)

