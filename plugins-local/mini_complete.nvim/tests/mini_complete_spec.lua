test('auto-import edits that only arrive on resolve are applied, and the completion lands below them', function()
  local mc = H.reset()
  mc.setup({ luasnip = false })
  local server = H.fake_server({
    complete = function() return items({ label = 'StringBuilder' }) end,
    resolve = function(item)
      item.additionalTextEdits = { { range = { start = { line = 0, character = 0 }, ['end'] = { line = 0, character = 0 } }, newText = 'using System.Text;\n' } }
      return item
    end,
  })
  H.buffer(server)
  H.feed('ivar sb = new Str')
  H.wait_until(mc.is_visible)
  H.feed('<CR>')
  H.sleep(150)
  eq({ 'using System.Text;', 'var sb = new StringBuilder' }, vim.api.nvim_buf_get_lines(0, 0, -1, false))
  eq(1, server.count('completionItem/resolve'))
  eq({ 2, #'var sb = new StringBuilder' }, vim.api.nvim_win_get_cursor(0))
end)
