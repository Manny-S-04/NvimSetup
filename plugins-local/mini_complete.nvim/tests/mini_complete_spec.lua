-- ── trigger characters ──────────────────────────────────────────────────────────────────────────
test('an allowlisted trigger (".") opens with no word typed and tells the server which character', function()
  local mc = H.reset()
  mc.setup({ luasnip = false })
  local server = H.fake_server({ complete = function() return items({ label = 'Length' }) end })
  H.buffer(server)
  H.feed('iname.')
  ok(H.wait_until(mc.is_visible), 'bar opened after "."')
  local req = server.requests[#server.requests]
  eq('textDocument/completion', req.method)
  eq({ triggerKind = 2, triggerCharacter = '.' }, req.params.context)
end)

test('a trigger the server advertises but the allowlist does not (space) does not open the bar', function()
  local mc = H.reset()
  mc.setup({ luasnip = false })
  local server = H.fake_server({ complete = function() return items({ label = 'x' }) end })
  H.buffer(server)
  H.feed('ireturn ')
  H.sleep(150)
  local after_space = vim.tbl_filter(function(r)
    return r.method == 'textDocument/completion' and r.params.context.triggerKind == 2
  end, server.requests)
  eq(0, #after_space)
  eq(false, mc.is_visible())
end)

-- ── keys ────────────────────────────────────────────────────────────────────────────────────────
test('<C-j> / <C-k> move the selection and wrap around', function()
  local mc = H.reset()
  mc.setup({ luasnip = false })
  H.buffer(H.fake_server({ complete = function() return items({ label = 'a1' }, { label = 'a2' }, { label = 'a3' }) end }))
  H.feed('ia')
  H.wait_until(mc.is_visible)
  eq(1, mc._state.selected)
  H.feed('<C-j><C-j>')
  eq(3, mc._state.selected)
  H.feed('<C-j>')
  eq(1, mc._state.selected, 'wraps forward')
  H.feed('<C-k>')
  eq(3, mc._state.selected, 'wraps backward')
end)

test('<Esc> closes the bar and still leaves insert mode', function()
  local mc = H.reset()
  mc.setup({ luasnip = false })
  H.buffer(H.fake_server({ complete = function() return items({ label = 'Alpha' }) end }))
  H.feed('iAl')
  H.wait_until(mc.is_visible)
  H.feed('<Esc>')
  H.wait_until(function() return vim.fn.mode() == 'n' end)
  eq(false, mc.is_visible())
  eq('n', vim.fn.mode())
end)

